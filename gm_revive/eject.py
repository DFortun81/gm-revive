"""Eject: turn a converted project into a plain JavaScript source tree that is developed directly,
with no GML and no GameMaker project file any more.

    python -m gm_revive eject game.gmk out/

out/ gets:
    src/game/resources.js     resource index constants (spr_x = 3, obj_y = 12, ...) and user constants
    src/game/scripts/*.js     one file per script, with the GML comments carried over
    src/game/world.js         SCRIPT_LIST, the OBJECTS table, timelines, paths and rooms
    src/game/objects/*.js     one file per object: its properties and events
    src/runtime/runtime.js    the engine (yours to change from here on)
    src/index.html            the page
    assets/                   sprites, backgrounds and sounds, plus assets.json describing them
    files/                    extra files the game loads at runtime
    build.py                  joins all of that into html5/ (no dependencies)
    html5/                    a first build
The comments come over at statement level: a trailing comment (code; // note) moves to its own line
under the statement, and comments inside a multi-line expression move to before the next statement.
"""
import json
import os
import shutil

from .build import convert, FILE_MARK, RUNTIME_DIR
from .rtf2html import rtf_to_html

BUILD_PY = r'''"""Build html5/ from src/ and assets/ (no dependencies; Python 3.8+).

    python build.py

The game is plain JavaScript now (ejected from the 2013 GameMaker project by gm-revive):
  src/game/resources.js   resource index constants (spr_*, obj_*, snd_*, ...) and user constants
  src/game/scripts/       one file per script:  S.name = function name(self, other, argument0, ...) {...}
  src/game/world.js       SCRIPT_LIST, the OBJECTS table, timelines, paths, rooms
  src/game/objects/       one file per object:  OBJECTS[obj_x] = { name, sprite, parent, ..., events: {...} }
  src/runtime/runtime.js  the engine (GameMaker's API as B.*)
  assets/assets.json      sprites, backgrounds, sounds and fonts; their position in each list is their index
html5/game.js is resources.js + scripts + world.js + objects joined in that order; images.js embeds
every PNG as a data: URI so index.html also works straight from disk.
"""
import base64
import glob
import json
import os
import shutil

here = os.path.dirname(os.path.abspath(__file__))
src = os.path.join(here, 'src')
out = os.path.join(here, 'html5')


def read(path):
    with open(path, encoding='utf-8') as fh:
        return fh.read().rstrip('\n') + '\n'


def main():
    os.makedirs(out, exist_ok=True)
    g = os.path.join(src, 'game')
    parts = ['// Battlefield: built by build.py from src/ (edit src/, not this file)\n', read(os.path.join(g, 'resources.js'))]
    parts += [read(f) for f in sorted(glob.glob(os.path.join(g, 'scripts', '*.js')))]
    parts.append(read(os.path.join(g, 'world.js')))
    parts += [read(f) for f in sorted(glob.glob(os.path.join(g, 'objects', '*.js')))]
    with open(os.path.join(here, 'assets', 'assets.json'), encoding='utf-8') as fh:
        assets = json.load(fh)
    parts.append('const ASSETS = ' + json.dumps(assets, indent=1) + ';\n')
    files_dir = os.path.join(here, 'files')
    extra = sorted(f for f in os.listdir(files_dir) if os.path.isfile(os.path.join(files_dir, f))) if os.path.isdir(files_dir) else []
    parts.append('const EXTRA_FILES = ' + json.dumps(extra) + ';\n')
    with open(os.path.join(out, 'game.js'), 'w', encoding='utf-8', newline='\n') as fh:
        fh.write(''.join(parts))

    # assets/ and files/ are copied as they are (stale files removed)
    for d in ('assets', 'files'):
        dst = os.path.join(out, d)
        if os.path.isdir(dst):
            shutil.rmtree(dst)
        if os.path.isdir(os.path.join(here, d)):
            shutil.copytree(os.path.join(here, d), dst, ignore=shutil.ignore_patterns('assets.json'))
    imgs = {}
    for root in ('assets/sprites', 'assets/backgrounds', 'files'):
        d = os.path.join(out, root)
        if os.path.isdir(d):
            for f in sorted(os.listdir(d)):
                if f.lower().endswith('.png'):
                    with open(os.path.join(d, f), 'rb') as fh:
                        imgs[root + '/' + f] = 'data:image/png;base64,' + base64.b64encode(fh.read()).decode()
    with open(os.path.join(out, 'images.js'), 'w', encoding='utf-8', newline='\n') as fh:
        fh.write('// Embedded image data (generated by build.py)\nconst IMAGE_DATA = ' + json.dumps(imgs) + ';\n')
    shutil.copy(os.path.join(src, 'runtime', 'runtime.js'), os.path.join(out, 'runtime.js'))
    shutil.copy(os.path.join(src, 'index.html'), os.path.join(out, 'index.html'))
    print('Wrote ' + os.path.join(out, 'index.html'))


if __name__ == '__main__':
    main()
'''


def eject(gmk_path, out_dir, extra_dir=None, soundfont=None, overrides=None, log=print):
    html5 = os.path.join(out_dir, 'html5')
    conv = convert(gmk_path, html5, extra_dir=extra_dir, soundfont=soundfont, log=log,
                   overrides=overrides, keep_comments=True)
    game = os.path.join(out_dir, 'src', 'game')
    for d in ('scripts', 'objects'):
        os.makedirs(os.path.join(game, d), exist_ok=True)
    files = {'resources.js': []}
    cur = 'resources.js'
    for line in conv.js:
        if line.startswith(FILE_MARK):
            cur = line[len(FILE_MARK):]
            files.setdefault(cur, [])
            continue
        files[cur].append(line)
    for rel, lines in files.items():
        if rel == 'resources.js':
            lines = [l for l in lines if not l.startswith('// Generated by gm-revive')]
        with open(os.path.join(game, rel), 'w', encoding='utf-8', newline='\n') as fh:
            fh.write('\n'.join(lines).strip('\n') + '\n')

    os.makedirs(os.path.join(out_dir, 'src', 'runtime'), exist_ok=True)
    shutil.copy(os.path.join(RUNTIME_DIR, 'runtime.js'), os.path.join(out_dir, 'src', 'runtime', 'runtime.js'))
    shutil.copy(os.path.join(html5, 'index.html'), os.path.join(out_dir, 'src', 'index.html'))
    # assets/ (the build's own copy is the source from now on) and the asset list
    for d in ('assets', 'files'):
        dst = os.path.join(out_dir, d)
        if os.path.isdir(dst):
            shutil.rmtree(dst)
        if os.path.isdir(os.path.join(html5, d)):
            shutil.copytree(os.path.join(html5, d), dst)
    os.makedirs(os.path.join(out_dir, 'assets'), exist_ok=True)
    with open(os.path.join(out_dir, 'assets', 'assets.json'), 'w', encoding='utf-8', newline='\n') as fh:
        json.dump(conv.meta, fh, indent=1)
        fh.write('\n')
    with open(os.path.join(out_dir, 'build.py'), 'w', encoding='utf-8', newline='\n') as fh:
        fh.write(BUILD_PY)
    return conv
